import hashlib, os, sys, zlib

# Generates sdk/tools/bs_native_modules.h from a directory of bs-<kmi>.ko files.
# Each module is zlib-compressed and XOR-obfuscated with a per-KMI key so the
# header (and therefore the loader binary) carries no plain .ko image.

OUT = sys.argv[1] if len(sys.argv) > 1 else "sdk/tools/bs_native_modules.h"
SRC = sys.argv[2] if len(sys.argv) > 2 else "modules"

KMIS = [
    ("android12-5.10", "5.10"),
    ("android13-5.15", "5.15"),
    ("android14-6.1", "6.1"),
    ("android15-6.6", "6.6"),
    ("android16-6.12", "6.12"),
    ("android17-6.18", "6.18"),
]


def xor_key(name):
    digest = hashlib.sha256(name.encode()).digest()
    return digest[0] or 0x5a


entries = []
for kmi, series in KMIS:
    path = os.path.join(SRC, "bs-%s.ko" % kmi)
    if not os.path.exists(path):
        sys.exit("missing module artifact: %s" % path)
    with open(path, "rb") as handle:
        raw = handle.read()
    if not raw.startswith(b"\x7fELF"):
        sys.exit("%s is not an ELF file" % path)
    digest = hashlib.sha256(raw).hexdigest()
    sidecar = path + ".sha256"
    if os.path.exists(sidecar):
        with open(sidecar, "r", encoding="utf-8") as handle:
            declared = handle.read().split()[0].strip().lower()
        if declared != digest:
            sys.exit("%s does not match its .sha256 sidecar" % path)
    comp = zlib.compress(raw, 9)
    key = xor_key(kmi)
    enc = bytes(b ^ key for b in comp)
    entries.append((kmi, series, enc, key, raw, hashlib.sha256(raw).hexdigest()))
    print("%s: raw=%d compressed=%d" % (kmi, len(raw), len(comp)))

with open(OUT, "w", encoding="utf-8") as out:
    out.write("/* Generated by sdk/tools/gen_embedded_modules.py; do not edit. */\n")
    out.write("#ifndef BSKERNEL_NATIVE_MODULES_H\n#define BSKERNEL_NATIVE_MODULES_H\n\n")
    out.write("struct embedded_module {\n")
    out.write("    const char* kmi;\n    const char* series;\n")
    out.write("    const unsigned char* data;\n    unsigned int size;\n")
    out.write("    unsigned char xor_key;\n    unsigned int raw_size;\n")
    out.write("    const char* sha256;\n};\n\n")
    for index, entry in enumerate(entries):
        enc = entry[2]
        out.write("static const unsigned char bs_module_%d[] = {\n" % index)
        for offset in range(0, len(enc), 16):
            chunk = ", ".join("0x%02x" % value for value in enc[offset:offset + 16])
            out.write("    %s,\n" % chunk)
        out.write("};\n\n")
    out.write("static const struct embedded_module embedded_modules[] = {\n")
    for index, (kmi, series, enc, key, raw, digest) in enumerate(entries):
        out.write(
            '    { "%s", "%s", bs_module_%d, %du, 0x%02x, %du, "%s" },\n'
            % (kmi, series, index, len(enc), key, len(raw), digest)
        )
    out.write("};\n\n")
    out.write("static const unsigned int embedded_module_count = %du;\n\n" % len(entries))
    out.write("#endif /* BSKERNEL_NATIVE_MODULES_H */\n")

print("wrote %s" % OUT)